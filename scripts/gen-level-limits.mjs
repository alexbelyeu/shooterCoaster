// node scripts/gen-level-limits.mjs: api/_lib/levelLimits.ts from src/levels/scoreLimits.ts (api/ can't import src/ on Vercel).
import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import os from 'node:os'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outFile = path.join(root, 'api/_lib/levelLimits.ts')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sc-limits-'))
const bundle = path.join(tmp, 'limits.mjs')

await build({
  stdin: { contents: "export { campaignScoreLimits } from '@/levels/scoreLimits'", resolveDir: root, loader: 'ts' },
  bundle: true,
  format: 'esm',
  platform: 'node',
  alias: { '@': path.join(root, 'src') },
  outfile: bundle,
  logLevel: 'error',
})
const { campaignScoreLimits } = await import(pathToFileURL(bundle).href)
fs.rmSync(tmp, { recursive: true, force: true })

const limits = campaignScoreLimits()
const body = `// Generated by scripts/gen-level-limits.mjs from src/levels/scoreLimits.ts: do not edit by hand.
// What each field means: ScoreLimits in src/levels/scoreLimits.ts.

export interface ScoreLimits {
  maxScore: number
  maxKills: number
  maxKillPoints: number
}

export const LEVEL_LIMITS: Readonly<Record<string, ScoreLimits>> = ${JSON.stringify(limits, null, 2)}
`
fs.writeFileSync(outFile, body)
console.log(`wrote ${path.relative(root, outFile)}: ${Object.keys(limits).join(', ')}`)
