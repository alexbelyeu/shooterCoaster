// node scripts/gen-ocean-level.mjs: src/levels/environments/biomes/ocean/oceanLevel.ts, level 1's ride (#863) as plain
// numbers, from `oceanTrack.ts`. The level registry is startup JS; the ride elements that build the ride aren't.
import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import os from 'node:os'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outFile = path.join(root, 'src/levels/environments/biomes/ocean/oceanLevel.ts')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sc-ocean-'))
const bundle = path.join(tmp, 'ocean.mjs')

await build({
  stdin: { contents: "export { OCEAN_TRACK } from '@/levels/environments/biomes/ocean/oceanTrack'", resolveDir: root, loader: 'ts' },
  bundle: true,
  format: 'esm',
  platform: 'node',
  alias: { '@': path.join(root, 'src') },
  outfile: bundle,
  logLevel: 'error',
})
const { OCEAN_TRACK } = await import(pathToFileURL(bundle).href)
fs.rmSync(tmp, { recursive: true, force: true })

/**
 * Positions to whole world units (the eye is 6 over the rails), a rail's up to 2 decimals, the rest to 6 significant digits:
 * full doubles cost the startup JS ~2 KB gz more. `oceanLevel.test.ts` rounds the same way.
 */
const round = (_key, v) => (typeof v === 'number' ? Number(v.toPrecision(6)) : v)
const roundPoint = (p) => {
  const q = { x: Math.round(p.x) + 0, y: Math.round(p.y) + 0, z: Math.round(p.z) + 0 }
  return p.up ? { ...q, up: { x: Number(p.up.x.toFixed(2)) + 0, y: Number(p.up.y.toFixed(2)) + 0, z: Number(p.up.z.toFixed(2)) + 0 } } : q
}

const rest = JSON.parse(JSON.stringify({ ...OCEAN_TRACK, controlPoints: undefined }, round))
const controlPoints = OCEAN_TRACK.controlPoints.map(roundPoint)
const xyz = controlPoints.flatMap((p, i) => (i ? [p.x - controlPoints[i - 1].x, p.y - controlPoints[i - 1].y, p.z - controlPoints[i - 1].z] : [p.x, p.y, p.z]))
const ups = controlPoints.flatMap((p, i) => (p.up ? [i, p.up.x, p.up.y, p.up.z] : []))
const body = `// Generated by scripts/gen-ocean-level.mjs from oceanTrack.ts: do not edit by hand.
// Level 3's ride as plain numbers, so the ride elements that build it stay out of the startup JS; the control points as flat
// lists (x, y, z of the first, then each one's step from the last; index, x, y, z of each rolled one's up): the steps
// repeat along a straight, so they gzip ~1 KB smaller than objects.
import type { RailPoint } from '@/track/curves/SplineCurve'
import type { TrackParams } from '@/types/level'

const XYZ = ${JSON.stringify(xyz)}
const UPS = ${JSON.stringify(ups)}

function controlPoints(): RailPoint[] {
  const points: RailPoint[] = []
  let [x, y, z] = [0, 0, 0]
  for (let i = 0; i < XYZ.length; i += 3) points.push({ x: (x += XYZ[i]), y: (y += XYZ[i + 1]), z: (z += XYZ[i + 2]) })
  for (let i = 0; i < UPS.length; i += 4) points[UPS[i]].up = { x: UPS[i + 1], y: UPS[i + 2], z: UPS[i + 3] }
  return points
}

export const OCEAN_LEVEL_TRACK: TrackParams = { ...${JSON.stringify(rest)}, curve: 'spline', controlPoints: controlPoints() } as TrackParams
`
fs.writeFileSync(outFile, body)
console.log(`wrote ${path.relative(root, outFile)}: ${OCEAN_TRACK.controlPoints.length} control points`)
