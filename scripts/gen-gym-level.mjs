// node scripts/gen-gym-level.mjs: src/levels/environments/biomes/gym/gymLevel.ts, level 6's track and climbable walls as plain
// numbers, from the blockout (`gymTrack.ts`, `walls.ts`). The level registry is startup JS, the blockout isn't (#589).
import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import os from 'node:os'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outFile = path.join(root, 'src/levels/environments/biomes/gym/gymLevel.ts')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sc-gym-'))
const bundle = path.join(tmp, 'gym.mjs')

await build({
  stdin: {
    contents: "export { GYM_TRACK } from '@/levels/environments/biomes/gym/gymTrack'\nexport { GYM_WALLS } from '@/levels/environments/biomes/gym/walls'",
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  alias: { '@': path.join(root, 'src') },
  outfile: bundle,
  logLevel: 'error',
})
const { GYM_TRACK, GYM_WALLS } = await import(pathToFileURL(bundle).href)
fs.rmSync(tmp, { recursive: true, force: true })

/** Numbers to 6 significant digits (under 1e-2 world units in the hall, 0.3 mm): full doubles cost the startup JS ~0.3 KB gz more. */
const round = (_key, v) => (typeof v === 'number' ? Number(v.toPrecision(6)) : v)

const { controlPoints, ...track } = JSON.parse(JSON.stringify(GYM_TRACK, round))
const xyz = controlPoints.flatMap((p) => [p.x, p.y, p.z])
const ups = controlPoints.flatMap((p, i) => (p.up ? [i, p.up.x, p.up.y, p.up.z] : []))
const body = `// Generated by scripts/gen-gym-level.mjs from gymTrack.ts and walls.ts: do not edit by hand.
// Level 6's ride and climbable walls without the blockout, so the level registry keeps it out of the startup JS (#589); the
// control points as flat lists (x, y, z of each; index, x, y, z of each rolled one's up), ~2 KB gz smaller than objects.
import type { RailPoint } from '@/track/curves/SplineCurve'
import type { TrackParams, WallSurface } from '@/types/level'

const XYZ = ${JSON.stringify(xyz)}
const UPS = ${JSON.stringify(ups)}

function controlPoints(): RailPoint[] {
  const points: RailPoint[] = []
  for (let i = 0; i < XYZ.length; i += 3) points.push({ x: XYZ[i], y: XYZ[i + 1], z: XYZ[i + 2] })
  for (let i = 0; i < UPS.length; i += 4) points[UPS[i]].up = { x: UPS[i + 1], y: UPS[i + 2], z: UPS[i + 3] }
  return points
}

export const GYM_LEVEL: { track: TrackParams; walls: readonly WallSurface[] } = {
  track: { ...${JSON.stringify(track)}, curve: 'spline', controlPoints: controlPoints() } as TrackParams,
  walls: ${JSON.stringify(JSON.parse(JSON.stringify(GYM_WALLS, round)))},
}
`
fs.writeFileSync(outFile, body)
console.log(`wrote ${path.relative(root, outFile)}: ${GYM_TRACK.controlPoints.length} control points, ${GYM_WALLS.length} walls`)
