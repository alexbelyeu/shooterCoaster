// node scripts/gen-gym-level.mjs: src/levels/environments/biomes/gym/gymLevel.ts, level 6's track and climbable walls as plain
// numbers, from the blockout (`gymTrack.ts`, `walls.ts`). The level registry is startup JS, the blockout isn't (#589).
import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import os from 'node:os'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outFile = path.join(root, 'src/levels/environments/biomes/gym/gymLevel.ts')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sc-gym-'))
const bundle = path.join(tmp, 'gym.mjs')

await build({
  stdin: {
    contents: "export { GYM_TRACK } from '@/levels/environments/biomes/gym/gymTrack'\nexport { GYM_WALLS } from '@/levels/environments/biomes/gym/walls'",
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  alias: { '@': path.join(root, 'src') },
  outfile: bundle,
  logLevel: 'error',
})
const { GYM_TRACK, GYM_WALLS } = await import(pathToFileURL(bundle).href)
fs.rmSync(tmp, { recursive: true, force: true })

/** Numbers to 7 significant digits (under 1e-3 world units in the hall, 30 µm): full doubles cost the startup JS ~0.3 KB gz more. */
const round = (_key, v) => (typeof v === 'number' ? Number(v.toPrecision(7)) : v)

const body = `// Generated by scripts/gen-gym-level.mjs from gymTrack.ts and walls.ts: do not edit by hand.
// Level 6's ride and climbable walls without the blockout, so the level registry keeps it out of the startup JS (#589).
import type { TrackParams, WallSurface } from '@/types/level'

export const GYM_LEVEL: { track: TrackParams; walls: readonly WallSurface[] } = ${JSON.stringify({ track: GYM_TRACK, walls: GYM_WALLS }, round, 2)}
`
fs.writeFileSync(outFile, body)
console.log(`wrote ${path.relative(root, outFile)}: ${GYM_TRACK.controlPoints.length} control points, ${GYM_WALLS.length} walls`)
