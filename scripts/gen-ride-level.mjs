// node scripts/gen-ride-level.mjs: each ride built from the ride kit as plain numbers the level registry imports: level 1's
// (#863, `parkTrack.ts` -> `parkLevel.ts`) and level 2's (#864, `desertTrack.ts` -> `desertLevel.ts`). The level registry is
// startup JS; the ride elements that build the rides aren't.
import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import os from 'node:os'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
/**
 * Each ride: the track file and its export, the generated file and its export, the level it is, and (`yaw`) the export
 * that turns a ride laid out in its own frame into the world: its points ship in that frame, where a straight's steps repeat.
 */
const RIDES = [
  { dir: 'themePark', track: 'parkTrack', from: 'PARK_TRACK', out: 'parkLevel', to: 'PARK_LEVEL_TRACK', level: 'Level 1' },
  { dir: 'desert', track: 'desertTrack', from: 'DESERT_TRACK', out: 'desertLevel', to: 'DESERT_LEVEL_TRACK', level: 'Level 2', yaw: 'DESERT_RIDE_YAW' },
]
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sc-ride-'))
const bundle = path.join(tmp, 'rides.mjs')

await build({
  stdin: {
    contents: RIDES.map((r) => `export { ${[r.from, r.yaw].filter(Boolean).join(', ')} } from '@/levels/environments/biomes/${r.dir}/${r.track}'`).join('\n'),
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  alias: { '@': path.join(root, 'src') },
  outfile: bundle,
  logLevel: 'error',
})
const tracks = await import(pathToFileURL(bundle).href)
fs.rmSync(tmp, { recursive: true, force: true })

/**
 * Positions to whole world units (the eye is 6 over the rails), a rail's up to 2 decimals, the rest to 6 significant digits:
 * full doubles cost the startup JS ~2 KB gz more. `parkLevel.test.ts` and `desertLevel.test.ts` round the same way.
 */
const round = (_key, v) => (typeof v === 'number' ? Number(v.toPrecision(6)) : v)
/** A world point (or up) in the frame turned by `yaw`: the inverse of the level file's `toWorld`. */
const toFrame = (p, yaw) => ({ x: p.x * Math.cos(yaw) - p.z * Math.sin(yaw), y: p.y, z: p.x * Math.sin(yaw) + p.z * Math.cos(yaw) })
const roundPoint = (p) => {
  const q = { x: Math.round(p.x) + 0, y: Math.round(p.y) + 0, z: Math.round(p.z) + 0 }
  return p.up ? { ...q, up: { x: Number(p.up.x.toFixed(2)) + 0, y: Number(p.up.y.toFixed(2)) + 0, z: Number(p.up.z.toFixed(2)) + 0 } } : q
}

for (const r of RIDES) {
  const track = tracks[r.from]
  const yaw = r.yaw ? tracks[r.yaw] : 0
  const rest = JSON.parse(JSON.stringify({ ...track, controlPoints: undefined }, round))
  const inFrame = (p) => (p.up ? { ...toFrame(p, yaw), up: toFrame(p.up, yaw) } : toFrame(p, yaw))
  const controlPoints = track.controlPoints.map((p) => roundPoint(yaw ? inFrame(p) : p))
  const xyz = controlPoints.flatMap((p, i) => (i ? [p.x - controlPoints[i - 1].x, p.y - controlPoints[i - 1].y, p.z - controlPoints[i - 1].z] : [p.x, p.y, p.z]))
  const ups = controlPoints.flatMap((p, i) => (p.up ? [i, p.up.x, p.up.y, p.up.z] : []))
  const body = `// Generated by scripts/gen-ride-level.mjs from ${r.track}.ts: do not edit by hand.
// ${r.level}'s ride as plain numbers, so the ride elements that build it stay out of the startup JS; the control points as flat
// lists (x, y, z of the first, then each one's step from the last; index, x, y, z of each rolled one's up): the steps
// repeat along a straight, so they gzip ~1 KB smaller than objects.${yaw ? `
// The ride is laid out in its own frame (\`${r.track}.ts\`), turned \`YAW\` about y into the world: its points ship in that frame.` : ''}
import type { RailPoint } from '@/track/curves/SplineCurve'
import type { TrackParams } from '@/types/level'

const XYZ = ${JSON.stringify(xyz)}
const UPS = ${JSON.stringify(ups)}
${yaw ? `const YAW = ${yaw}
const toWorld = (x: number, y: number, z: number) => ({ x: x * Math.cos(YAW) + z * Math.sin(YAW), y, z: -x * Math.sin(YAW) + z * Math.cos(YAW) })
` : `const toWorld = (x: number, y: number, z: number) => ({ x, y, z })
`}
function controlPoints(): RailPoint[] {
  const points: RailPoint[] = []
  let [x, y, z] = [0, 0, 0]
  for (let i = 0; i < XYZ.length; i += 3) points.push(toWorld((x += XYZ[i]), (y += XYZ[i + 1]), (z += XYZ[i + 2])))
  for (let i = 0; i < UPS.length; i += 4) points[UPS[i]].up = toWorld(UPS[i + 1], UPS[i + 2], UPS[i + 3])
  return points
}

export const ${r.to}: TrackParams = { ...${JSON.stringify(rest)}, curve: 'spline', controlPoints: controlPoints() } as TrackParams
`
  const outFile = path.join(root, `src/levels/environments/biomes/${r.dir}/${r.out}.ts`)
  fs.writeFileSync(outFile, body)
  console.log(`wrote ${path.relative(root, outFile)}: ${track.controlPoints.length} control points`)
}
